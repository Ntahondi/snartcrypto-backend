    @staticmethod
    def _direction_matches(
        direction: str,
        action: str,
    ) -> bool:

        direction = str(
            direction
        ).upper()

        action = str(
            action
        ).upper()

        if direction in {
            "BUY",
            "LONG",
            "UP",
            "BULLISH",
        }:

            return action == "BUY"

        if direction in {
            "SELL",
            "SHORT",
            "DOWN",
            "BEARISH",
        }:

            return action == "SELL"

        return False

    def _extract_probability(
        self,
        data: Any,
    ) -> Optional[float]:

        if not isinstance(
            data,
            dict,
        ):
            return None

        keys = (
            "probability",
            "prob",
            "confidence",
            "win_probability",
            "direction_probability",
        )

        for key in keys:

            if key not in data:
                continue

            value = self._safe_float(
                data.get(
                    key
                ),
                None,
            )

            if value is None:
                continue

            # Accept percentages such as 55.
            if value > 1.0 and value <= 100.0:
                value /= 100.0

            if 0.0 <= value <= 1.0:
                return float(value)

        return None

    def _extract_expected_return(
        self,
        signal: Dict[str, Any],
    ) -> Optional[float]:

        expected = signal.get(
            "expected_returns"
        )

        if isinstance(
            expected,
            dict,
        ):

            preferred_keys = (
                "4h_return",
                "1h_return",
                "12h_return",
                "expected_return",
            )

            for key in preferred_keys:

                if key not in expected:
                    continue

                return self._parse_percentage(
                    expected[key]
                )

        direct = signal.get(
            "expected_return"
        )

        if direct is not None:

            return self._parse_percentage(
                direct
            )

        return None

