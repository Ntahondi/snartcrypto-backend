def confidence_value(
    value: Any,
) -> float:
    """
    Safely normalize AI confidence values to [0, 1].
    """

    try:

        result = float(
            value
        )

        if not math.isfinite(
            result
        ):
            return 0.0

        return float(
            np.clip(
                result,
                0.0,
                1.0,
            )
        )

    except (
        TypeError,
        ValueError,
    ):

        return 0.0


