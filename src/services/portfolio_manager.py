    def _schedule_real_open(
        self,
        position: Position,
    ) -> None:

        if not self.trade_executor:
            return

        try:

            loop = asyncio.get_running_loop()

            task = loop.create_task(
                self._execute_open_safely(
                    position
                )
            )

            self._track_execution_task(
                task
            )

        except RuntimeError as exc:

            position.execution_status = (
                "EXECUTION_NOT_SCHEDULED"
            )

            self._save_position(
                position
            )

            logger.error(
                f"❌ Could not schedule "
                f"real open: {exc}"
            )

