    def _update_signal_outcome(
        self,
        position: Position,
    ) -> None:

        if (
            not self.history_manager
            or not position.signal_id
        ):
            return

        try:

            pnl = position.pnl or 0.0

            outcome = (
                "WIN"
                if pnl > 0
                else (
                    "LOSS"
                    if pnl < 0
                    else "BREAKEVEN"
                )
            )

            self.history_manager.update_signal_outcome(
                position.signal_id,
                outcome,
                pnl=position.pnl,
                pnl_percentage=position.pnl_percentage,
                exit_price=position.exit_price,
                exit_time=position.exit_time,
                position_id=position.id,
            )

        except Exception as exc:

            logger.warning(
                f"⚠️ Could not update "
                f"signal outcome: {exc}"
            )

