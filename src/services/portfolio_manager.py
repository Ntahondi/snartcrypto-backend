    def _load_positions(
        self,
    ) -> None:
        """
        Recover the latest state of every position.

        A CLOSED snapshot always overrides an older OPEN snapshot.
        """

        if not os.path.exists(
            self.trade_history_file
        ):
            return

        latest: Dict[
            str,
            Dict[str, Any],
        ] = {}

        try:

            with open(
                self.trade_history_file,
                "r",
                encoding="utf-8",
            ) as file:

                for line_number, line in enumerate(
                    file,
                    start=1,
                ):

                    line = line.strip()

                    if not line:
                        continue

                    try:

                        data = json.loads(
                            line
                        )

                    except json.JSONDecodeError as exc:

                        logger.warning(
                            f"⚠️ Invalid trade-history "
                            f"line {line_number}: {exc}"
                        )

                        continue

                    position_id = data.get(
                        "id"
                    )

                    if not position_id:
                        continue

                    latest[
                        str(position_id)
                    ] = data

            for data in latest.values():

                position = (
                    self._position_from_dict(
                        data
                    )
                )

                if not position:
                    continue

                if position.status == "OPEN":

                    existing = (
                        self.open_positions.get(
                            position.symbol
                        )
                    )

                    if existing:

                        existing_time = (
                            self._ensure_aware_datetime(
                                existing.entry_time
                            )
                        )

                        new_time = (
                            self._ensure_aware_datetime(
                                position.entry_time
                            )
                        )

                        if new_time <= existing_time:
                            continue

                    self.open_positions[
                        position.symbol
                    ] = position

                elif position.status == "CLOSED":

                    self.closed_positions.append(
                        position
                    )

            logger.info(
                f"📂 Loaded "
                f"{len(self.open_positions)} "
                f"active positions and "
                f"{len(self.closed_positions)} "
                f"closed positions."
            )

            self._reconstruct_daily_state()

        except Exception as exc:

            logger.error(
                f"❌ Error loading positions: "
                f"{exc}",
                exc_info=True,
            )

