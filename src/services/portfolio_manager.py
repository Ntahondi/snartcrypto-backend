    def set_profile(self, profile_name: str) -> Tuple[bool, str]:
        """Dynamically switch trading profile and reconfigure risk gates."""
        try:
            from src.core.trading_profiles import get_profile
            new_profile = get_profile(profile_name)
            self.profile = new_profile
            self.profile_name = str(profile_name).lower()
            style = self._profile_value("trading_style", self.profile_name)
            risk = self._profile_value("risk_tolerance", "unknown")
            logger.info(f"🔄 Trading Profile dynamically switched to: {style} (Risk: {risk})")
            return True, f"Trading profile successfully switched to {self.profile_name}"
        except Exception as exc:
            logger.error(f"❌ Failed to switch trading profile to {profile_name}: {exc}")
            return False, str(exc)

    # =========================================================
    # PROFILE HELPERS
    # =========================================================

    def _profile_value(
        self,
        field: str,
        default: Any,
    ) -> Any:
        """Return a profile value while unwrapping Enum values."""

        value = getattr(
            self.profile,
            field,
            default,
        )

        return getattr(
            value,
            "value",
            value,
        )

    def _profile_float(
        self,
        field: str,
        default: float,
    ) -> float:

        try:
            value = float(
                self._profile_value(
                    field,
                    default,
                )
            )

            if not math.isfinite(value):
                return float(default)

            return value

        except (
            TypeError,
            ValueError,
        ):
            return float(default)

    def _profile_bool(
        self,
        field: str,
        default: bool,
    ) -> bool:

        return bool(
            self._profile_value(
                field,
                default,
            )
        )

    def _profile_int(
        self,
        field: str,
        default: int,
    ) -> int:

        try:
            return int(
                self._profile_value(
                    field,
                    default,
                )
            )

        except (
            TypeError,
            ValueError,
        ):
            return int(default)

    # =========================================================
    # REAL TRADE EXECUTOR
    # =========================================================

    def _initialize_trade_executor(
        self,
    ) -> None:
        """
        Initialize the real trade executor safely.

        Failure here must never crash PortfolioManager.
        """

        try:

            self.settings = get_settings()

            executor = RealTradeExecutor(
                self.settings
            )

            self.trade_executor = executor

            enabled = bool(
                getattr(
                    executor,
                    "enable_real_trading",
                    False,
                )
            )

            if enabled:

                logger.warning(
                    "⚠️ REAL TRADING EXECUTION IS ENABLED."
                )

                try:

                    loop = asyncio.get_running_loop()

                    task = loop.create_task(
                        executor.initialize()
                    )

                    self._track_execution_task(
                        task
                    )

                except RuntimeError:

                    logger.warning(
                        "⚠️ No running event loop. "
                        "Real executor initialization "
                        "must be completed later."
                    )

            else:

                logger.info(
                    "📝 Real trading disabled. "
                    "Portfolio running in paper mode."
                )

        except Exception as exc:

            self.trade_executor = None

            logger.warning(
                f"⚠️ RealTradeExecutor disabled: {exc}"
            )

    def _real_trading_enabled(
        self,
    ) -> bool:

        return bool(
            self.trade_executor
            and getattr(
                self.trade_executor,
                "enable_real_trading",
                False,
            )
        )

    # =========================================================
    # DAILY STATE
    # =========================================================

    def _reset_daily_state_if_needed(
        self,
    ) -> None:

        today = datetime.now(
            timezone.utc
        ).date()

        if today == self.today:
            return

        self.today = today

        self.daily_trades = 0

        self.daily_pnl = 0.0

        logger.info(
            "🌅 Daily portfolio limits reset."
        )

    # =========================================================
    # POSITION SIZING
    # =========================================================

    def calculate_position_size(
        self,
        signal: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Calculate position size.

        Uses:

        - profile allocation
        - Kelly sizing when enabled
        - AI confidence
        - signal strength
        - available capital
        - ATR-based SL/TP
        - strategy-provided SL/TP when available
        """

        symbol = str(
            signal.get(
                "symbol",
                "",
            )
        ).strip()

        action = str(
            signal.get(
                "action",
                "",
            )
        ).upper()

        if not symbol:
            raise ValueError(
                "Missing symbol."
            )

        if action not in {
            "BUY",
            "SELL",
        }:
            raise ValueError(
                f"Invalid trading action: {action}"
            )

        try:

            entry_price = float(
                signal.get(
                    "price",
                    0.0,
                )
            )

        except (
            TypeError,
            ValueError,
        ):

            entry_price = 0.0

        if (
            entry_price <= 0
            or not math.isfinite(entry_price)
        ):
            raise ValueError(
                f"Invalid entry price: {entry_price}"
            )

        confidence = float(
            np.clip(
                self._safe_float(
                    signal.get(
                        "confidence",
                        0.5,
                    ),
                    0.5,
                ),
                0.0,
                1.0,
            )
        )

        strength = float(
            np.clip(
                self._safe_float(
                    signal.get(
                        "signal_strength",
                        0.5,
                    ),
                    0.5,
                ),
                0.0,
                1.0,
            )
        )

        # -----------------------------------------------------
        # Base profile allocation
        # -----------------------------------------------------

        base_profile_pct = self._profile_float(
            "position_size_pct",
            0.05,
        )

        if base_profile_pct <= 0:
            raise ValueError(
                "Profile position_size_pct must be greater than zero."
            )

        # -----------------------------------------------------
        # Kelly
        # -----------------------------------------------------

        if self._profile_bool(
            "use_kelly_sizing",
            False,
        ):

            expected_win_rate = self._profile_float(
                "expected_win_rate",
                0.5,
            )

            adjusted_win_rate = (
                expected_win_rate
                * (
                    1.0
                    + (
                        confidence
                        - 0.4
                    )
                    * 2.0
                )
            )

            adjusted_win_rate = float(
                np.clip(
                    adjusted_win_rate,
                    0.35,
                    0.75,
                )
            )

            position_pct = float(
                self.profile.calculate_kelly_optimal_position(
                    adjusted_win_rate
                )
            )

        else:

            position_pct = (
                base_profile_pct
            )

        # -----------------------------------------------------
        # AI confidence scaling
        # -----------------------------------------------------

        confidence_scalar = float(
            np.clip(
                0.5
                + (
                    confidence
                    - 0.3
                )
                * 2.5,
                0.5,
                1.5,
            )
        )

        position_pct *= (
            confidence_scalar
        )

        # -----------------------------------------------------
        # Signal strength scaling
        # -----------------------------------------------------

        strength_scalar = (
            0.8
            + strength * 0.4
        )

        position_pct *= (
            strength_scalar
        )

        # -----------------------------------------------------
        # Profile limits
        # -----------------------------------------------------

        # TradingProfile v3.1 defines the base position size.
        #
        # Kelly itself already applies its own internal bounds.
        # Therefore the manager uses a conservative 40%-150%
        # envelope around the profile base allocation.

        min_position_pct = (
            base_profile_pct * 0.40
        )

        max_position_pct = (
            base_profile_pct * 1.50
        )

        position_pct = float(
            np.clip(
                position_pct,
                min_position_pct,
                max_position_pct,
            )
        )

        # -----------------------------------------------------
        # Available capital
        # -----------------------------------------------------

        if self.available_capital <= 0:
            raise ValueError(
                "No available capital."
            )

        allocation_usd = (
            self.available_capital
            * position_pct
        )

        if allocation_usd <= 0:
            raise ValueError(
                "Calculated allocation is zero."
            )

        allocation_usd = min(
            allocation_usd,
            self.available_capital,
        )

        quantity = (
            allocation_usd
            / entry_price
        )

        if (
            quantity <= 0
            or not math.isfinite(quantity)
        ):
            raise ValueError(
                "Calculated quantity is invalid."
            )

        # -----------------------------------------------------
        # ATR
        # -----------------------------------------------------

        atr = self._get_atr(
            symbol
        )

        sl_atr_mult = self._profile_float(
            "stop_loss_atr_mult",
            1.5,
        )

        tp_atr_mult = self._profile_float(
            "take_profit_atr_mult",
            3.0,
        )

        # -----------------------------------------------------
        # Percentage fallback
        # -----------------------------------------------------

        profile_sl_pct = 0.02
        profile_tp_pct = 0.04

        # -----------------------------------------------------
        # Strategy-provided SL/TP
        # -----------------------------------------------------

        strategy = signal.get(
            "strategy",
            {}
        )

        if not isinstance(
            strategy,
            dict,
        ):
            strategy = {}

        signal_sl = strategy.get(
            "stop_loss"
        )

        signal_tp = strategy.get(
            "take_profit_1"
        )

        # -----------------------------------------------------
        # Stop loss
        # -----------------------------------------------------

        if self._valid_positive_number(
            signal_sl
        ):

            stop_loss = float(
                signal_sl
            )

        elif (
            atr is not None
            and atr > 0
        ):

            if action == "BUY":

                stop_loss = (
                    entry_price
                    - atr * sl_atr_mult
                )

            else:

                stop_loss = (
                    entry_price
                    + atr * sl_atr_mult
                )

        else:

            if action == "BUY":

                stop_loss = (
                    entry_price
                    * (
                        1.0
                        - profile_sl_pct
                    )
                )

            else:

                stop_loss = (
                    entry_price
                    * (
                        1.0
                        + profile_sl_pct
                    )
                )

        # -----------------------------------------------------
        # Take profit
        # -----------------------------------------------------

        if self._valid_positive_number(
            signal_tp
        ):

            take_profit = float(
                signal_tp
            )

        elif (
            atr is not None
            and atr > 0
        ):

            if action == "BUY":

                take_profit = (
                    entry_price
                    + atr * tp_atr_mult
                )

            else:

                take_profit = (
                    entry_price
                    - atr * tp_atr_mult
                )

        else:

            if action == "BUY":

                take_profit = (
                    entry_price
                    * (
                        1.0
                        + profile_tp_pct
                    )
                )

            else:

                take_profit = (
                    entry_price
                    * (
                        1.0
                        - profile_tp_pct
                    )
                )

        # -----------------------------------------------------
        # Risk geometry validation
        # -----------------------------------------------------

        if not self._valid_positive_number(
            stop_loss
        ):
            raise ValueError(
                "Stop-loss is invalid."
            )

        if not self._valid_positive_number(
            take_profit
        ):
            raise ValueError(
                "Take-profit is invalid."
            )

        if action == "BUY":

            if stop_loss >= entry_price:
                raise ValueError(
                    "BUY stop-loss must be below entry price."
                )

            if take_profit <= entry_price:
                raise ValueError(
                    "BUY take-profit must be above entry price."
                )

        else:

            if stop_loss <= entry_price:
                raise ValueError(
                    "SELL stop-loss must be above entry price."
                )

            if take_profit >= entry_price:
                raise ValueError(
                    "SELL take-profit must be below entry price."
                )

        return {
            "position_size_pct": float(
                position_pct
            ),
            "allocation_usd": float(
                allocation_usd
            ),
            "quantity": float(
                quantity
            ),
            "entry_price": float(
                entry_price
            ),
            "stop_loss": float(
                stop_loss
            ),
            "take_profit": float(
                take_profit
            ),
            "max_holding_hours": self._profile_int(
                "max_holding_hours",
                8,
            ),
            "atr_used": (
                float(atr)
                if atr is not None
                else None
            ),
            "kelly_size": float(
                position_pct
            ),
        }

    # =========================================================
    # ATR
    # =========================================================

    def _get_atr(
        self,
        symbol: str,
    ) -> Optional[float]:
        """Return current ATR without unsafe hard-coded ATR values."""

        cached = self.atr_values.get(
            symbol
        )

        if (
            cached is not None
            and cached > 0
            and math.isfinite(cached)
        ):
            return float(cached)

        df = self.market_data.get(
            symbol
        )

        if df is None:
            return None

        try:

            if (
                df.empty
                or "atr14" not in df.columns
            ):
                return None

            atr = float(
                df[
                    "atr14"
                ].iloc[-1]
            )

            if (
                math.isfinite(atr)
                and atr > 0
            ):

                self.atr_values[
                    symbol
                ] = atr

                return atr

        except Exception as exc:

            logger.warning(
                f"⚠️ ATR calculation failed "
                f"for {symbol}: {exc}"
            )

        return None

    # =========================================================
    # FINAL RISK GATE
    # =========================================================

    def should_open_position(
        self,
        signal: Dict[str, Any],
    ) -> Tuple[bool, str]:
        """
        FINAL PORTFOLIO RISK GATE.

        Every proposed trade must pass this method.

        The gate uses the TradingProfile wherever possible.
        """

        self._reset_daily_state_if_needed()

        symbol = str(
            signal.get(
                "symbol",
                "",
            )
        ).strip()

        action = str(
            signal.get(
                "action",
                "HOLD",
            )
        ).upper()

        if not symbol:
            return False, "Missing symbol"

        if action not in {
            "BUY",
            "SELL",
        }:
            return False, (
                f"Invalid action: {action}"
            )

        # -----------------------------------------------------
        # Gate 1: Confidence
        # -----------------------------------------------------

        confidence = float(
            np.clip(
                self._safe_float(
                    signal.get(
                        "confidence",
                        0.0,
                    ),
                    0.0,
                ),
                0.0,
                1.0,
            )
        )

        min_confidence = self._profile_float(
            "min_confidence",
            0.40,
        )

        if confidence < min_confidence:

            return False, (
                f"Confidence too low: "
                f"{confidence:.1%} < "
                f"{min_confidence:.1%}"
            )

        # -----------------------------------------------------
        # Gate 2: Signal strength
        # -----------------------------------------------------

        strength = float(
            np.clip(
                self._safe_float(
                    signal.get(
                        "signal_strength",
                        0.0,
                    ),
                    0.0,
                ),
                0.0,
                1.0,
            )
        )

        min_strength = self._profile_float(
            "min_signal_strength",
            0.35,
        )

        if strength < min_strength:

            return False, (
                f"Signal strength too low: "
                f"{strength:.1%} < "
                f"{min_strength:.1%}"
            )

        # -----------------------------------------------------
        # Gate 3: Committee / ensemble agreement
        # -----------------------------------------------------

        votes = signal.get(
            "votes",
            {}
        )

        if not isinstance(
            votes,
            dict,
        ):
            votes = {}

        vote_tag = str(
            votes.get(
                "tag",
                "",
            )
        ).upper()

        majority = str(
            votes.get(
                "majority",
                "",
            )
        )

        if self._profile_bool(
            "require_ensemble_agreement",
            False,
        ):

            if vote_tag not in {
                "2/3 MAJORITY",
                "3/3 UNANIMOUS",
            }:

                return False, (
                    "Required ensemble agreement "
                    "was not achieved."
                )

        # -----------------------------------------------------
        # Gate 4: Timeframe alignment
        # -----------------------------------------------------

        if self._profile_bool(
            "require_timeframe_alignment",
            False,
        ):

            if not self._timeframe_alignment_ok(
                signal
            ):

                return False, (
                    "Required timeframe alignment "
                    "was not achieved."
                )

        # -----------------------------------------------------
        # Gate 5: Smart Trader requirements
        # -----------------------------------------------------

        if self._profile_bool(
            "use_smart_trader_model",
            True,
        ):

            smart_trader = self._get_model_breakdown(
                signal,
                "model_2_smart_trader",
            )

            if self._profile_bool(
                "require_4h_direction",
                False,
            ):

                direction_4h = str(
                    smart_trader.get(
                        "4h_direction",
                        smart_trader.get(
                            "direction_4h",
                            smart_trader.get(
                                "direction",
                                "",
                            ),
                        ),
                    )
                ).upper()

                if direction_4h:

                    if not self._direction_matches(
                        direction_4h,
                        action,
                    ):

                        return False, (
                            "Smart Trader 4H "
                            "direction conflicts "
                            "with signal."
                        )

            if self._profile_bool(
                "require_1d_confirmation",
                False,
            ):

                direction_1d = str(
                    smart_trader.get(
                        "1d_direction",
                        smart_trader.get(
                            "direction_1d",
                            "",
                        ),
                    )
                ).upper()

                if direction_1d:

                    if not self._direction_matches(
                        direction_1d,
                        action,
                    ):

                        return False, (
                            "Smart Trader 1D "
                            "confirmation conflicts "
                            "with signal."
                        )

        # -----------------------------------------------------
        # Gate 6: Market GPT
        # -----------------------------------------------------

        if self._profile_bool(
            "use_market_gpt_model",
            True,
        ):

            market_gpt = self._get_model_breakdown(
                signal,
                "model_3_market_gpt",
            )

            if not market_gpt:

                market_gpt = self._get_model_breakdown(
                    signal,
                    "market_gpt",
                )

            probability = self._extract_probability(
                market_gpt
            )

            min_probability = self._profile_float(
                "min_market_gpt_probability",
                0.55,
            )

            if (
                probability is not None
                and probability < min_probability
            ):

                return False, (
                    "Market GPT probability "
                    f"too low: "
                    f"{probability:.1%} < "
                    f"{min_probability:.1%}"
                )

        # -----------------------------------------------------
        # Gate 7: Expected return
        # -----------------------------------------------------

        if self._profile_bool(
            "use_regression_model",
            True,
        ):

            expected_return = self._extract_expected_return(
                signal
            )

            min_expected_return = self._profile_float(
                "min_expected_return",
                0.0,
            )

            if (
                expected_return is not None
                and expected_return
                < min_expected_return
            ):

                return False, (
                    "Expected return below "
                    f"profile minimum: "
                    f"{expected_return:.3%} < "
                    f"{min_expected_return:.3%}"
                )

        # -----------------------------------------------------
        # Gate 8: Model 4 strategy detector
        # -----------------------------------------------------

        if self._profile_bool(
            "use_model4_strategy_detector",
            True,
        ):

            accepted, reason = (
                self._validate_model4_signal(
                    signal
                )
            )

            if not accepted:
                return False, reason

        # -----------------------------------------------------
        # Gate 9: Risk level
        # -----------------------------------------------------

        risk_level = str(
            signal.get(
                "risk_level",
                "MEDIUM",
            )
        ).upper()

        if risk_level == "HIGH":

            return False, (
                "HIGH-risk setup rejected."
            )

        # -----------------------------------------------------
        # Gate 10: Funding conflict
        # -----------------------------------------------------

        derivatives = signal.get(
            "derivatives",
            {}
        )

        if not isinstance(
            derivatives,
            dict,
        ):
            derivatives = {}

        funding_rate = self._safe_float(
            derivatives.get(
                "funding_rate",
                0.0,
            ),
            0.0,
        )

        funding_conflict_threshold = 0.005

        if (
            action == "BUY"
            and funding_rate
            > funding_conflict_threshold
        ):

            return False, (
                "Funding rate conflicts "
                "with BUY."
            )

        if (
            action == "SELL"
            and funding_rate
            < -funding_conflict_threshold
        ):

            return False, (
                "Funding rate conflicts "
                "with SELL."
            )

        # -----------------------------------------------------
        # Gate 11: Order book conflict
        # -----------------------------------------------------

        orderbook = signal.get(
            "orderbook",
            {}
        )

        if not isinstance(
            orderbook,
            dict,
        ):
            orderbook = {}

        imbalance = self._safe_float(
            orderbook.get(
                "imbalance",
                0.0,
            ),
            0.0,
        )

        if (
            action == "BUY"
            and imbalance < -0.30
        ):

            return False, (
                "Order-book selling pressure "
                "conflicts with BUY."
            )

        if (
            action == "SELL"
            and imbalance > 0.30
        ):

            return False, (
                "Order-book buying pressure "
                "conflicts with SELL."
            )

        # -----------------------------------------------------
        # Gate 12: Existing position & Explicit Reversal
        # -----------------------------------------------------

        active = self._active_positions()

        existing = active.get(
            symbol
        )

        if existing:
            existing_action = str(getattr(existing, "action", "")).upper()
            is_opposite = (
                (action in {"BUY", "LONG"} and existing_action in {"SELL", "SHORT"})
                or (action in {"SELL", "SHORT"} and existing_action in {"BUY", "LONG"})
            )
            if not is_opposite:
                return False, (
                    f"Position already open for {symbol} in same direction ({existing_action}). "
                    "Duplicate entry rejected."
                )
            logger.info(
                f"🔄 Explicit Reversal Approved for {symbol}: Incoming {action} will close existing {existing_action}"
            )

        # -----------------------------------------------------
        # Gate 13: Maximum total positions
        # -----------------------------------------------------

        profile_max_positions = self._profile_int(
            "max_total_positions",
            10,
        )

        max_positions = min(
            profile_max_positions,
            self.MAX_POSITIONS_HARD_CAP,
        )

        if len(active) >= max_positions:

            return False, (
                "Maximum open positions reached: "
                f"{len(active)}/{max_positions}"
            )

        # -----------------------------------------------------
        # Gate 14: Daily trade limit
        # -----------------------------------------------------

        max_daily_trades = self._profile_int(
            "max_daily_trades",
            10,
        )

        if (
            max_daily_trades > 0
            and self.daily_trades
            >= max_daily_trades
        ):

            return False, (
                "Daily trade limit reached: "
                f"{self.daily_trades}/"
                f"{max_daily_trades}"
            )

        # -----------------------------------------------------
        # Gate 15: Minimum time between trades
        # -----------------------------------------------------

        min_interval = self._profile_int(
            "min_time_between_trades",
            0,
        )

        if min_interval > 0:

            last_trade = self.last_trade_time.get(
                symbol
            )

            if last_trade is not None:

                last_trade = (
                    self._ensure_aware_datetime(
                        last_trade
                    )
                )

                elapsed = (
                    datetime.now(
                        timezone.utc
                    )
                    - last_trade
                ).total_seconds()

                if elapsed < min_interval:

                    remaining = (
                        min_interval
                        - elapsed
                    )

                    return False, (
                        "Minimum trade interval "
                        f"not elapsed. "
                        f"{remaining:.0f}s remaining."
                    )

        # -----------------------------------------------------
        # Gate 16: Daily loss
        # -----------------------------------------------------

        max_daily_loss_pct = self._profile_float(
            "max_daily_loss_pct",
            0.05,
        )

        max_daily_loss = (
            self.initial_capital
            * max_daily_loss_pct
        )

        if (
            max_daily_loss_pct >= 0
            and self.daily_pnl
            <= -max_daily_loss
        ):

            return False, (
                "Daily loss protection triggered: "
                f"${abs(self.daily_pnl):.2f}"
            )

        # -----------------------------------------------------
        # Gate 17: Maximum drawdown
        # -----------------------------------------------------

        max_drawdown_pct = self._profile_float(
            "max_drawdown_pct",
            0.20,
        )

        if (
            max_drawdown_pct >= 0
            and self.current_drawdown
            >= max_drawdown_pct
        ):

            return False, (
                "Maximum portfolio drawdown "
                "protection triggered: "
                f"{self.current_drawdown:.2%}"
            )

        # -----------------------------------------------------
        # Gate 18: Capital
        # -----------------------------------------------------

        min_allocation = (
            self.initial_capital
            * self.DEFAULT_MIN_ALLOCATION_PCT
        )

        if (
            self.available_capital
            < min_allocation
        ):

            return False, (
                "Insufficient available capital: "
                f"${self.available_capital:.2f}"
            )

        # -----------------------------------------------------
        # Gate 19: Price
        # -----------------------------------------------------

        price = self._safe_float(
            signal.get(
                "price",
                0,
            ),
            0.0,
        )

        if (
            price <= 0
            or not math.isfinite(price)
        ):

            return False, (
                "Invalid signal price."
            )

        # -----------------------------------------------------
        # Gate 20: Duplicate signal
        # -----------------------------------------------------

        signal_id = signal.get(
            "signal_id"
        )

        if signal_id:

            signal_id = str(
                signal_id
            )

            for position in (
                self.open_positions.values()
            ):

                if (
                    position.status == "OPEN"
                    and position.signal_id
                    == signal_id
                ):

                    return False, (
                        f"Signal {signal_id} "
                        "already has an open position."
                    )

        return True, (
            "Passed all portfolio "
            "risk gates."
        )

    # =========================================================
    # MODEL 4 VALIDATION
    # =========================================================

    def _validate_model4_signal(
        self,
        signal: Dict[str, Any],
    ) -> Tuple[bool, str]:
        """
        Apply Model 4 strategy-detector profile rules.

        Supported TradingProfile controls:

        - model4_min_strategy_probability
        - model4_strong_strategy_probability
        - model4_min_active_strategies
        - model4_max_active_strategies
        - model4_require_strong_strategy
        - model4_require_strategy_confirmation
        """

        model4 = signal.get(
            "model4",
            signal.get(
                "model_4",
                signal.get(
                    "strategy_detector",
                    {},
                ),
            ),
        )

        if not isinstance(
            model4,
            dict,
        ):
            model4 = {}

        strategies = model4.get(
            "active_strategies",
            model4.get(
                "strategies",
                [],
            ),
        )

        if isinstance(
            strategies,
            dict,
        ):

            normalized_strategies = []

            for name, data in strategies.items():

                if isinstance(
                    data,
                    dict,
                ):

                    probability = (
                        self._extract_probability(
                            data
                        )
                    )

                else:

                    probability = self._safe_float(
                        data,
                        None,
                    )

                normalized_strategies.append(
                    {
                        "name": str(name),
                        "probability": (
                            probability
                            if probability is not None
                            else 0.0
                        ),
                    }
                )

            strategies = normalized_strategies

        elif isinstance(
            strategies,
            list,
        ):

            normalized_strategies = []

            for item in strategies:

                if isinstance(
                    item,
                    str,
                ):

                    normalized_strategies.append(
                        {
                            "name": item,
                            "probability": 1.0,
                        }
                    )

                elif isinstance(
                    item,
                    dict,
                ):

                    normalized_strategies.append(
                        {
                            "name": str(
                                item.get(
                                    "name",
                                    item.get(
                                        "strategy",
                                        "unknown",
                                    ),
                                )
                            ),
                            "probability": (
                                self._extract_probability(
                                    item
                                )
                                or 0.0
                            ),
                        }
                    )

            strategies = normalized_strategies

        else:

            strategies = []

        # -----------------------------------------------------
        # Filter enabled strategies from TradingProfile
        # -----------------------------------------------------

        enabled_strategies = getattr(
            self.profile,
            "model4_enabled_strategies",
            None,
        )

        if enabled_strategies:

            enabled_set = {
                str(name).lower()
                for name in enabled_strategies
            }

            strategies = [
                item
                for item in strategies
                if str(
                    item["name"]
                ).lower()
                in enabled_set
            ]

        min_probability = self._profile_float(
            "model4_min_strategy_probability",
            0.50,
        )

        strong_probability = self._profile_float(
            "model4_strong_strategy_probability",
            0.75,
        )

        valid_strategies = [
            item
            for item in strategies
            if (
                self._safe_float(
                    item.get(
                        "probability",
                        0.0,
                    ),
                    0.0,
                )
                >= min_probability
            )
        ]

        active_count = len(
            valid_strategies
        )

        strongest_probability = max(
            (
                self._safe_float(
                    item.get(
                        "probability",
                        0.0,
                    ),
                    0.0,
                )
                for item in strategies
            ),
            default=0.0,
        )

        min_active = self._profile_int(
            "model4_min_active_strategies",
            1,
        )

        max_active = self._profile_int(
            "model4_max_active_strategies",
            9,
        )

        if active_count < min_active:

            return False, (
                "Model 4 active-strategy "
                f"requirement failed: "
                f"{active_count} < {min_active}"
            )

        if max_active > 0 and active_count > max_active:

            return False, (
                "Model 4 active-strategy "
                f"limit exceeded: "
                f"{active_count} > {max_active}"
            )

        if self._profile_bool(
            "model4_require_strong_strategy",
            False,
        ):

            if strongest_probability < strong_probability:

                return False, (
                    "Model 4 strong-strategy "
                    "requirement failed."
                )

        # -----------------------------------------------------
        # Strategy confirmation
        # -----------------------------------------------------

        if self._profile_bool(
            "model4_require_strategy_confirmation",
            False,
        ):

            confirmed = bool(
                model4.get(
                    "strategy_confirmation",
                    model4.get(
                        "confirmed",
                        False,
                    ),
                )
            )

            if not confirmed:

                return False, (
                    "Model 4 strategy confirmation "
                    "required but not present."
                )

        # -----------------------------------------------------
        # Direction vote
        # -----------------------------------------------------

        if self._profile_bool(
            "model4_use_as_direction_vote",
            False,
        ):

            action = str(
                signal.get(
                    "action",
                    "",
                )
            ).upper()

            model4_direction = str(
                model4.get(
                    "direction",
                    model4.get(
                        "signal",
                        "",
                    ),
                )
            ).upper()

            if model4_direction:

                if not self._direction_matches(
                    model4_direction,
                    action,
                ):

                    return False, (
                        "Model 4 direction vote "
                        "conflicts with trade."
                    )

        return True, (
            "Model 4 strategy requirements passed."
        )

    # =========================================================
    # OPEN POSITION
    # =========================================================

    def open_position(
        self,
        signal: Dict[str, Any],
    ) -> Optional[Position]:
        """
        Create a paper/local position after passing the
        final portfolio gate.

        Real execution is scheduled only after the local
        state has been persisted.
        """

        symbol = str(
            signal.get(
                "symbol",
                "",
            )
        ).strip()

        action = str(
            signal.get(
                "action",
                "",
            )
        ).upper()

        if not symbol:
            logger.error(
                "❌ Cannot open position: "
                "missing symbol."
            )
            return None

        if action not in {
            "BUY",
            "SELL",
        }:
            logger.error(
                f"❌ Invalid action: {action}"
            )
            return None

        try:

            # -------------------------------------------------
            # Final risk gate
            # -------------------------------------------------

            should_trade, reason = (
                self.should_open_position(
                    signal
                )
            )

            if not should_trade:

                logger.info(
                    f"⏭️ Portfolio rejected "
                    f"{symbol}: {reason}"
                )

                return None

            # -------------------------------------------------
            # Position sizing
            # -------------------------------------------------

            pos_info = (
                self.calculate_position_size(
                    signal
                )
            )

            allocation = float(
                pos_info[
                    "allocation_usd"
                ]
            )

            if allocation <= 0:
                logger.warning(
                    f"⚠️ Zero allocation "
                    f"for {symbol}"
                )
                return None

            # -------------------------------------------------
            # Critical state mutation
            # -------------------------------------------------

            # This section is protected with a process-level
            # lock when called from async code through
            # open_position_async().
            #
            # For synchronous callers, the final duplicate
            # check immediately before mutation remains active.

            existing = self.open_positions.get(
                symbol
            )

            if (
                existing is not None
                and existing.status == "OPEN"
            ):
                existing_action = str(getattr(existing, "action", "")).upper()
                is_opposite = (
                    (action in {"BUY", "LONG"} and existing_action in {"SELL", "SHORT"})
                    or (action in {"SELL", "SHORT"} and existing_action in {"BUY", "LONG"})
                )
                if is_opposite:
                    logger.info(
                        f"🔄 Executing clean reversal for {symbol}: Closing existing {existing_action} to open {action}"
                    )
                    self.close_position(
                        symbol,
                        float(pos_info.get("entry_price", existing.current_price)),
                        "REVERSED_BY_OPPOSITE_SIGNAL",
                    )
                else:
                    logger.warning(
                        f"🛡️ Duplicate position blocked for {symbol}"
                    )
                    return None

            if allocation > self.available_capital:

                logger.warning(
                    f"⚠️ Allocation exceeds "
                    f"available capital "
                    f"for {symbol}"
                )

                return None

            # -------------------------------------------------
            # AI metadata
            # -------------------------------------------------

            expected_return = (
                self._extract_expected_return(
                    signal
                )
                or 0.0
            )

            votes = signal.get(
                "votes",
                {}
            )

            if not isinstance(
                votes,
                dict,
            ):
                votes = {}

            majority_text = str(
                votes.get(
                    "majority",
                    "0/0",
                )
            )

            ensemble_agreement = (
                self._parse_vote_ratio(
                    majority_text
                )
            )

            strategy = signal.get(
                "strategy",
                {}
            )

            if not isinstance(
                strategy,
                dict,
            ):
                strategy = {}

            expected_time_to_profit = (
                self._safe_float(
                    strategy.get(
                        "max_holding_hours",
                        pos_info[
                            "max_holding_hours"
                        ],
                    ),
                    float(
                        pos_info[
                            "max_holding_hours"
                        ]
                    ),
                )
            )

            market_regime = str(
                signal.get(
                    "market_regime",
                    self._get_model_breakdown(
                        signal,
                        "model_2_smart_trader",
                    ).get(
                        "market_regime",
                        "UNKNOWN",
                    ),
                )
            )

            now = datetime.now(
                timezone.utc
            )

            # -------------------------------------------------
            # Create position
            # -------------------------------------------------

            position = Position(

                id=str(
                    uuid.uuid4()
                ),

                symbol=symbol,

                action=action,

                entry_price=float(
                    pos_info[
                        "entry_price"
                    ]
                ),

                current_price=float(
                    pos_info[
                        "entry_price"
                    ]
                ),

                quantity=float(
                    pos_info[
                        "quantity"
                    ]
                ),

                entry_time=now,

                stop_loss=float(
                    pos_info[
                        "stop_loss"
                    ]
                ),

                take_profit=float(
                    pos_info[
                        "take_profit"
                    ]
                ),

                max_holding_hours=int(
                    pos_info[
                        "max_holding_hours"
                    ]
                ),

                session_id=self.session_id,

                signal_id=(
                    str(
                        signal.get(
                            "signal_id"
                        )
                    )
                    if signal.get(
                        "signal_id"
                    )
                    is not None
                    else None
                ),

                timeframe=self._profile_value(
                    "signal_timeframe",
                    "1h",
                ),

                profile_name=self._profile_value(
                    "trading_style",
                    self.profile_name,
                ),

                ai_confidence=confidence_value(
                    signal.get(
                        "confidence",
                        0.0,
                    )
                ),

                ai_signal_strength=confidence_value(
                    signal.get(
                        "signal_strength",
                        0.0,
                    )
                ),

                expected_return=float(
                    expected_return
                ),

                expected_time_to_profit=float(
                    expected_time_to_profit
                ),

                ensemble_agreement=float(
                    ensemble_agreement
                ),

                market_regime=market_regime,

                execution_status=(
                    "PENDING_EXECUTION"
                    if self._real_trading_enabled()
                    else "PAPER_OPEN"
                ),
            )

            # -------------------------------------------------
            # Reserve capital
            # -------------------------------------------------

            self.available_capital -= (
                allocation
            )

            self.available_capital = max(
                self.available_capital,
                0.0,
            )

            self.open_positions[
                symbol
            ] = position

            self.last_trade_time[
                symbol
            ] = now

            self.daily_trades += 1

            self._update_drawdown()

            # -------------------------------------------------
            # Persist BEFORE external execution
            # -------------------------------------------------

            self._save_position(
                position
            )

            logger.info(
                f"🎯 POSITION CREATED | "
                f"{symbol} {action} | "
                f"Allocation: "
                f"${allocation:.2f} | "
                f"Entry: "
                f"${position.entry_price:.8f} | "
                f"SL: "
                f"${position.stop_loss:.8f} | "
                f"TP: "
                f"${position.take_profit:.8f} | "
                f"Consensus: "
                f"{majority_text}"
            )

            # -------------------------------------------------
            # Real execution
            # -------------------------------------------------

            if self._real_trading_enabled():

                self._schedule_real_open(
                    position
                )

            return position

        except Exception as exc:

            logger.error(
                f"❌ Failed to open position "
                f"for {symbol}: {exc}",
                exc_info=True,
            )

            return None

    async def open_position_async(
        self,
        signal: Dict[str, Any],
    ) -> Optional[Position]:
        """
        Async-safe wrapper for position creation.

        Use this from async trading loops when possible.
        """

        async with self._portfolio_lock:

            return self.open_position(
                signal
            )

    # =========================================================
    # POSITION MONITORING
    # =========================================================

    def monitor_position(
        self,
        symbol: str,
        current_price: float,
    ) -> Optional[str]:
        """
        Update position mark-to-market state and close when:

        - stop-loss is reached
        - take-profit is reached
        - maximum holding time expires

        Returns the close reason when closed.
        """

        try:

            current_price = float(
                current_price
            )

            if (
                current_price <= 0
                or not math.isfinite(current_price)
            ):
                return None

            position = (
                self.open_positions.get(
                    symbol
                )
            )

            if not position:
                return None

            if position.status != "OPEN":
                return None

            position.current_price = (
                current_price
            )

            # -------------------------------------------------
            # Unrealized PnL
            # -------------------------------------------------

            position.pnl = (
                self._calculate_pnl(
                    position,
                    current_price,
                )
            )

            notional = (
                position.entry_price
                * position.quantity
            )

            if notional > 0:
                position.pnl_percentage = (
                    position.pnl
                    / notional
                ) * 100.0

            pnl_pct = position.pnl_percentage or 0.0

            # -------------------------------------------------
            # 0. Profile-Adaptive Shield Configuration
            # -------------------------------------------------
            prof_name = getattr(position, "profile_name", self.profile_name) or self.profile_name
            try:
                prof_cfg = get_profile(prof_name)
            except Exception:
                prof_cfg = self.profile

            t1_trigger = getattr(prof_cfg, "tier1_breakeven_trigger_pct", 2.0)
            t1_buffer = getattr(prof_cfg, "tier1_fee_buffer_pct", 0.2)
            t2_trigger = getattr(prof_cfg, "tier2_lock_trigger_pct", 3.5)
            t2_lock = getattr(prof_cfg, "tier2_profit_lock_pct", 1.8)
            t3_trigger = getattr(prof_cfg, "tier3_trail_trigger_pct", 6.0)
            t3_dist = getattr(prof_cfg, "tier3_trail_distance_pct", 1.5)
            rec_dip_max = getattr(prof_cfg, "recovery_shallow_dip_max_loss_pct", 1.5)
            rec_ext_hours = getattr(prof_cfg, "recovery_extension_hours", 2)
            rec_cap_hours = getattr(prof_cfg, "max_recovery_capped_hours", 6)

            # -------------------------------------------------
            # 1. AI Profit Shield: Track Peak High-Water Mark
            # -------------------------------------------------
            if pnl_pct > position.peak_pnl_percentage:
                position.peak_pnl_percentage = pnl_pct
                position.peak_price = current_price

            is_long = position.action in {"BUY", "LONG"}

            # -------------------------------------------------
            # 2. AI Profit Shield: Dynamic Trailing & Breakeven
            # -------------------------------------------------
            if position.peak_pnl_percentage >= t3_trigger:
                # Tier 3: Macro Dynamic Trailing Lock (e.g. Swing/Position runner)
                position.trail_tier = 3
                position.is_risk_free = True
                position.shield_status = "PROFIT_LOCKED"
                peak_p = position.peak_price or current_price
                trail_sl = peak_p * (1.0 - t3_dist / 100.0) if is_long else peak_p * (1.0 + t3_dist / 100.0)
                if (is_long and trail_sl > position.stop_loss) or (not is_long and trail_sl < position.stop_loss):
                    position.stop_loss = trail_sl
                    logger.info(
                        f"🚀 [AI Profit Shield - TIER 3 MACRO TRAIL] {symbol} ({prof_name}) Trailing SL raised to {trail_sl:.4f} ({t3_dist:.1f}% behind peak {peak_p:.4f})"
                    )
            elif position.peak_pnl_percentage >= t2_trigger:
                # Tier 2: Lock in guaranteed net profit
                if position.trail_tier < 2:
                    position.trail_tier = 2
                    position.is_risk_free = True
                    position.shield_status = "PROFIT_LOCKED"
                    locked_sl = position.entry_price * (1.0 + t2_lock / 100.0) if is_long else position.entry_price * (1.0 - t2_lock / 100.0)
                    if (is_long and locked_sl > position.stop_loss) or (not is_long and locked_sl < position.stop_loss):
                        position.stop_loss = locked_sl
                        logger.info(
                            f"💰 [AI Profit Shield - TIER 2] {symbol} ({prof_name}) Trailing SL locked to {locked_sl:.4f} (+{t2_lock:.1f}% profit guaranteed)"
                        )
            elif position.peak_pnl_percentage >= t1_trigger:
                # Tier 1: Move Stop-Loss to Breakeven (+ fee buffer)
                if position.trail_tier < 1:
                    position.trail_tier = 1
                    position.is_risk_free = True
                    position.shield_status = "RISK_FREE_BREAKEVEN"
                    breakeven_sl = position.entry_price * (1.0 + t1_buffer / 100.0) if is_long else position.entry_price * (1.0 - t1_buffer / 100.0)
                    if (is_long and breakeven_sl > position.stop_loss) or (not is_long and breakeven_sl < position.stop_loss):
                        position.stop_loss = breakeven_sl
                        logger.info(
                            f"🛡️ [AI Profit Shield - TIER 1] {symbol} ({prof_name}) SL raised to Profit-Lock {breakeven_sl:.4f} (+{t1_buffer:.1f}% Profit Guaranteed)"
                        )

            # -------------------------------------------------
            # Exit conditions
            # -------------------------------------------------

            exit_reason: Optional[
                str
            ] = None

            exit_price: Optional[
                float
            ] = None

            if is_long:
                if current_price <= position.stop_loss:
                    if position.trail_tier >= 2:
                        exit_reason = "TRAILING_PROFIT_LOCK"
                    elif position.trail_tier >= 1 or position.is_risk_free:
                        exit_reason = "DYNAMIC_BREAKEVEN"
                    else:
                        exit_reason = "STOP_LOSS"
                    exit_price = position.stop_loss
                elif current_price >= position.take_profit:
                    exit_reason = "TAKE_PROFIT"
                    exit_price = position.take_profit
            else:
                if current_price >= position.stop_loss:
                    if position.trail_tier >= 2:
                        exit_reason = "TRAILING_PROFIT_LOCK"
                    elif position.trail_tier >= 1 or position.is_risk_free:
                        exit_reason = "DYNAMIC_BREAKEVEN"
                    else:
                        exit_reason = "STOP_LOSS"
                    exit_price = position.stop_loss
                elif current_price <= position.take_profit:
                    exit_reason = "TAKE_PROFIT"
                    exit_price = position.take_profit

            # -------------------------------------------------
            # Maximum holding time & Smart Capped Recovery
            # -------------------------------------------------

            if exit_reason is None:
                now = datetime.now(timezone.utc)
                entry_time = self._ensure_aware_datetime(position.entry_time)
                hold_hours = (now - entry_time).total_seconds() / 3600.0

                if position.max_holding_hours > 0 and hold_hours >= position.max_holding_hours:
                    # Smart Recovery: If shallow dip and showed prior positive momentum, grant 1-time extension (capped at profile max)
                    if (
                        not position.extension_active
                        and position.peak_pnl_percentage >= (t1_trigger * 0.75)
                        and (-rec_dip_max <= pnl_pct <= -0.2)
                        and position.max_holding_hours < rec_cap_hours
                    ):
                        position.max_holding_hours = min(position.max_holding_hours + rec_ext_hours, rec_cap_hours)
                        position.extension_active = True
                        position.shield_status = "RECOVERY_EXTENDED"
                        logger.info(
                            f"⏳ [AI Profit Shield] {symbol} ({prof_name}) Shallow dip recovery extension granted (+{rec_ext_hours}h, max {rec_cap_hours}h cap). Peak was +{position.peak_pnl_percentage:.2f}%"
                        )
                    else:
                        exit_reason = "TIMEOUT_RECOVERY" if position.extension_active else "TIMEOUT"
                        exit_price = current_price

            # -------------------------------------------------
            # Close
            # -------------------------------------------------

            if (
                exit_reason is not None
                and exit_price is not None
            ):

                self.close_position(
                    symbol,
                    float(exit_price),
                    exit_reason,
                )

                return exit_reason

            # -------------------------------------------------
            # Persist current mark
            # -------------------------------------------------

            self._save_position(
                position
            )

            self._update_drawdown()

            return None

        except Exception as exc:

            logger.error(
                f"❌ Position monitoring failed "
                f"for {symbol}: {exc}",
                exc_info=True,
            )

            return None

    # =========================================================
    # CLOSE POSITION
    # =========================================================

    def close_position(
        self,
        symbol: str,
        exit_price: float,
        reason: str,
    ) -> Optional[Position]:
        """
        Close a local/paper position.

        Important:
        Local portfolio accounting is settled here.

        Real exchange closing is submitted separately.
        If exchange execution fails, the position is marked
        with EXCHANGE_CLOSE_FAILED so reconciliation can detect
        the discrepancy.
        """

        try:

            exit_price = float(
                exit_price
            )

            if (
                exit_price <= 0
                or not math.isfinite(exit_price)
            ):
                return None

            position = (
                self.open_positions.get(
                    symbol
                )
            )

            if not position:
                return None

            if position.status != "OPEN":
                return None

            # -------------------------------------------------
            # Final PnL
            # -------------------------------------------------

            final_pnl = (
                self._calculate_pnl(
                    position,
                    exit_price,
                )
            )

            notional = (
                position.entry_price
                * position.quantity
            )

            pnl_percentage = (
                (
                    final_pnl
                    / notional
                )
                * 100.0
                if notional > 0
                else 0.0
            )

            exit_time = datetime.now(
                timezone.utc
            )

            # -------------------------------------------------
            # Remove from active state
            # -------------------------------------------------

            self.open_positions.pop(
                symbol,
                None,
            )

            # -------------------------------------------------
            # Update position
            # -------------------------------------------------

            position.exit_price = (
                exit_price
            )

            position.exit_time = (
                exit_time
            )

            position.status = "CLOSED"

            position.current_price = (
                exit_price
            )

            position.pnl = (
                final_pnl
            )

            position.pnl_percentage = (
                pnl_percentage
            )

            position.close_reason = (
                str(reason)
            )

            # -------------------------------------------------
            # Capital settlement
            # -------------------------------------------------

            allocation = (
                position.entry_price
                * position.quantity
            )

            self.available_capital += (
                allocation
                + final_pnl
            )

            self.available_capital = max(
                self.available_capital,
                0.0,
            )

            self.daily_pnl += (
                final_pnl
            )

            self.closed_positions.append(
                position
            )

            self._update_drawdown()

            # -------------------------------------------------
            # Persist CLOSED state
            # -------------------------------------------------

            self._save_position(
                position
            )

            # -------------------------------------------------
            # History
            # -------------------------------------------------

            self._update_signal_outcome(
                position
            )

            # -------------------------------------------------
            # Real exchange execution
            # -------------------------------------------------

            if self._real_trading_enabled():

                position.execution_status = (
                    "PENDING_CLOSE_EXECUTION"
                )

                self._save_position(
                    position
                )

                self._schedule_real_close(
                    position,
                    str(reason),
                )

            # -------------------------------------------------
            # Telegram
            # -------------------------------------------------

            self._schedule_telegram_close(
                position
            )

            result = (
                "WIN"
                if final_pnl > 0
                else (
                    "LOSS"
                    if final_pnl < 0
                    else "BREAKEVEN"
                )
            )

            logger.info(
                f"📊 POSITION CLOSED | "
                f"{symbol} | "
                f"{result} | "
                f"PnL: ${final_pnl:.2f} "
                f"({pnl_percentage:.2f}%) | "
                f"Reason: {reason}"
            )

            return position

        except Exception as exc:

            logger.error(
                f"❌ Failed closing "
                f"{symbol}: {exc}",
                exc_info=True,
            )

            return None

    async def close_position_async(
        self,
        symbol: str,
        exit_price: float,
        reason: str,
    ) -> Optional[Position]:

        async with self._portfolio_lock:

            return self.close_position(
                symbol,
                exit_price,
                reason,
            )

    # =========================================================
    # PNL
    # =========================================================

    @staticmethod
    def _calculate_pnl(
        position: Position,
        price: float,
    ) -> float:

        if position.action == "BUY":

            return (
                price
                - position.entry_price
            ) * position.quantity

        return (
            position.entry_price
            - price
        ) * position.quantity

    # =========================================================
    # PORTFOLIO VALUE
    # =========================================================

    def get_portfolio_value(
        self,
    ) -> float:
        """
        Mark-to-market portfolio equity.

        Reserved capital is added back together with
        unrealized PnL for each open position.
        """

        total = float(
            self.available_capital
        )

        for position in (
            self.open_positions.values()
        ):

            if position.status != "OPEN":
                continue

            allocation = (
                position.entry_price
                * position.quantity
            )

            unrealized = (
                self._calculate_pnl(
                    position,
                    position.current_price,
                )
            )

            total += (
                allocation
                + unrealized
            )

        return float(
            max(
                total,
                0.0,
            )
        )

    # =========================================================
    # DRAWDOWN
    # =========================================================

    def _update_drawdown(
        self,
    ) -> None:

        value = (
            self.get_portfolio_value()
        )

        if value > self.peak_portfolio_value:

            self.peak_portfolio_value = (
                value
            )

        if (
            self.peak_portfolio_value > 0
        ):

            self.current_drawdown = (
                (
                    self.peak_portfolio_value
                    - value
                )
                / self.peak_portfolio_value
            )

        else:

            self.current_drawdown = 0.0

    # =========================================================
    # MONITORING LOOP
    # =========================================================

    async def start_monitoring(
        self,
        market_analyzer,
    ) -> None:
        """
        Start continuous position monitoring.

        This method is intended to be started as a task:

            manager._monitor_task = asyncio.create_task(
                manager.start_monitoring(analyzer)
            )
        """

        if self._monitor_running:

            logger.warning(
                "⚠️ Portfolio monitoring "
                "already running."
            )

            return

        self._monitor_running = True

        logger.info(
            "🔍 Portfolio position "
            "monitoring started."
        )

        try:

            while self._monitor_running:

                try:

                    await self._monitor_cycle(
                        market_analyzer
                    )

                except asyncio.CancelledError:

                    raise

                except Exception as exc:

                    logger.error(
                        f"❌ Portfolio monitor "
                        f"cycle failed: {exc}",
                        exc_info=True,
                    )

                await asyncio.sleep(
                    self.MONITOR_INTERVAL_SECONDS
                )

        finally:

            self._monitor_running = False

            logger.info(
                "🛑 Portfolio monitoring stopped."
            )

    def create_monitoring_task(
        self,
        market_analyzer,
    ) -> asyncio.Task:
        """
        Create and retain the portfolio monitoring task.
        """

        if (
            self._monitor_task is not None
            and not self._monitor_task.done()
        ):

            return self._monitor_task

        self._monitor_task = (
            asyncio.create_task(
                self.start_monitoring(
                    market_analyzer
                )
            )
        )

        return self._monitor_task

    async def _monitor_cycle(
        self,
        market_analyzer,
    ) -> None:

        # -----------------------------------------------------
        # Synchronize ATR values
        # -----------------------------------------------------

        for symbol in list(
            self.open_positions.keys()
        ):

            try:

                df = (
                    market_analyzer.market_data.get(
                        symbol
                    )
                )

                if (
                    df is not None
                    and not df.empty
                    and "atr14" in df.columns
                ):

                    atr = float(
                        df[
                            "atr14"
                        ].iloc[-1]
                    )

                    if (
                        math.isfinite(atr)
                        and atr > 0
                    ):

                        self.atr_values[
                            symbol
                        ] = atr

            except Exception as exc:

                logger.debug(
                    f"ATR update skipped "
                    f"for {symbol}: {exc}"
                )

        # -----------------------------------------------------
        # Monitor positions
        # -----------------------------------------------------

        for symbol, position in list(
            self.open_positions.items()
        ):

            if position.status != "OPEN":
                continue

            try:

                df = (
                    market_analyzer.market_data.get(
                        symbol
                    )
                )

                if (
                    df is None
                    or df.empty
                    or "close" not in df.columns
                ):
                    continue

                current_price = float(
                    df[
                        "close"
                    ].iloc[-1]
                )

                self.monitor_position(
                    symbol,
                    current_price,
                )

            except Exception as exc:

                logger.error(
                    f"❌ Failed monitoring "
                    f"{symbol}: {exc}",
                    exc_info=True,
                )

        self._update_drawdown()

    async def stop_monitoring(
        self,
    ) -> None:
        """Stop portfolio monitoring cleanly."""

        self._monitor_running = False

        task = self._monitor_task

        if (
            task is not None
            and not task.done()
            and task is not asyncio.current_task()
        ):

            task.cancel()

            with contextlib.suppress(
                asyncio.CancelledError
            ):

                await task

        self._monitor_task = None

