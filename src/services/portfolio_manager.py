    @staticmethod
    def _safe_float(
        value: Any,
        default: Optional[float],
    ) -> Optional[float]:

        try:

            result = float(
                value
            )

            if not math.isfinite(
                result
            ):
                return default

            return result

        except (
            TypeError,
            ValueError,
        ):

            return default

    @staticmethod
    def _valid_positive_number(
        value: Any,
    ) -> bool:

        parsed = PortfolioManager._safe_float(
            value,
            None,
        )

        return bool(
            parsed is not None
            and parsed > 0
            and math.isfinite(parsed)
        )

    @staticmethod
    def _parse_percentage(
        value: Any,
    ) -> Optional[float]:

        try:

            if value is None:
                return None

            if isinstance(
                value,
                str,
            ):

                cleaned = (
                    value
                    .strip()
                    .replace(
                        "%",
                        "",
                    )
                    .replace(
                        "+",
                        "",
                    )
                )

                if not cleaned:
                    return None

                number = float(
                    cleaned
                )

                return (
                    number / 100.0
                )

            number = float(
                value
            )

            if not math.isfinite(
                number
            ):
                return None

            return number

        except (
            TypeError,
            ValueError,
        ):

            return None

    @staticmethod
    def _parse_vote_ratio(
        value: str,
    ) -> float:

        try:

            left, right = (
                str(
                    value
                ).split(
                    "/"
                )
            )

            numerator = float(
                left.strip()
            )

            denominator = float(
                right.strip()
            )

            if denominator <= 0:
                return 0.0

            return float(
                numerator
                / denominator
            )

        except Exception:

            return 0.0

    @staticmethod
    def _datetime_to_iso(
        value: datetime,
    ) -> str:

        value = (
            PortfolioManager
            ._ensure_aware_datetime(
                value
            )
        )

        return value.isoformat()

    @staticmethod
    def _parse_datetime(
        value: str,
    ) -> datetime:

        parsed = datetime.fromisoformat(
            str(value).replace(
                "Z",
                "+00:00",
            )
        )

        return (
            PortfolioManager
            ._ensure_aware_datetime(
                parsed
            )
        )

    @staticmethod
    def _ensure_aware_datetime(
        value: datetime,
    ) -> datetime:

        if value.tzinfo is None:

            return value.replace(
                tzinfo=timezone.utc
            )

        return value.astimezone(
            timezone.utc
        )

    # =========================================================
    # SHUTDOWN
    # =========================================================

    async def cleanup(
        self,
    ) -> None:
        """Gracefully stop portfolio services."""

        logger.info(
            "🛑 Cleaning up PortfolioManager..."
        )

        await self.stop_monitoring()

        # -----------------------------------------------------
        # Cancel pending executor tasks
        # -----------------------------------------------------

        tasks = list(
            self._execution_tasks
        )

        for task in tasks:

            if not task.done():
                task.cancel()

        if tasks:

            await asyncio.gather(
                *tasks,
                return_exceptions=True,
            )

        self._execution_tasks.clear()

        # -----------------------------------------------------
        # Close executor
        # -----------------------------------------------------

        if self.trade_executor:

            try:

                close_method = getattr(
                    self.trade_executor,
                    "close",
                    None,
                )

                if close_method:

                    result = (
                        close_method()
                    )

                    if asyncio.iscoroutine(
                        result
                    ):

                        await result

            except Exception as exc:

                logger.debug(
                    f"Executor cleanup error: "
                    f"{exc}"
                )

        logger.info(
            "✅ PortfolioManager cleanup complete."
        )


