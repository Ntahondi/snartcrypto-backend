    def _recalculate_available_capital(
        self,
    ) -> None:
        """
        Recalculate reserved capital from open positions.

        This prevents a restart from resetting available capital
        to the full initial balance.
        """

        reserved = 0.0

        for position in (
            self.open_positions.values()
        ):

            if position.status != "OPEN":
                continue

            reserved += (
                position.entry_price
                * position.quantity
            )

        self.available_capital = max(
            self.initial_capital
            - reserved,
            0.0,
        )

    def _reconstruct_daily_state(
        self,
    ) -> None:
        """
        Reconstruct basic daily statistics from recovered
        closed positions.

        Only positions whose exit time falls on the current
        UTC date are included.
        """

        today = datetime.now(
            timezone.utc
        ).date()

        self.today = today

        self.daily_trades = 0

        self.daily_pnl = 0.0

        for position in (
            self.closed_positions
        ):

            if position.exit_time is None:
                continue

            exit_time = (
                self._ensure_aware_datetime(
                    position.exit_time
                )
            )

            if exit_time.date() != today:
                continue

            self.daily_trades += 1

            self.daily_pnl += (
                position.pnl or 0.0
            )

            self.last_trade_time[
                position.symbol
            ] = max(
                self.last_trade_time.get(
                    position.symbol,
                    datetime.min.replace(
                        tzinfo=timezone.utc
                    ),
                ),
                exit_time,
            )

